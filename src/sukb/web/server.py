@app.post("/api/spaces/{key}/pull")
def start_pull(key: str) -> dict[str, str]:
    config = get_config()
    if not config.is_enabled(key):
        raise HTTPException(403, detail=f"Space {key} is not enabled in sync_config.yaml (v1 = ITSAI only)")

    # Per-space lock: two simultaneous pulls of the same space would race on
    # the markdown files and .sync-state.json. Reject the second call instead.
    with JOBS_LOCK:
        active = [j for j in JOBS.values() if j.space_key == key and j.status in ("pending", "running")]
        if active:
            raise HTTPException(
                409,
                detail=f"Space {key} already has an active pull (job_id={active[0].job_id}). "
                       f"Wait for it to finish or cancel before starting another.",
            )
        job_id = uuid.uuid4().hex[:12]
        job = Job(job_id=job_id, space_key=key, started_at=_now())
        JOBS[job_id] = job

    threading.Thread(target=_run_pull, args=(job,), daemon=True).start()
    return {"job_id": job_id, "space_key": key}


def _run_pull(job: Job) -> None:
    job.status = "running"
    try:
        puller = get_puller_for_job()
        for evt in puller.pull_space(job.space_key):
            record = {"kind": evt.kind, "space_key": evt.space_key, "ts": _now(), **evt.payload}
            job.events.append(record)
            job.queue.put(record)
            if evt.kind == "completed":
                job.summary = evt.payload.get("summary")
        job.status = "done"
    except Exception as e:
        job.status = "failed"
        job.error = str(e)
        job.queue.put({"kind": "job_error", "error": str(e), "ts": _now()})
    finally:
        job.finished_at = _now()
        job.queue.put({"kind": "stream_end", "ts": _now()})


def get_puller_for_job() -> ConfluencePuller:
    email, token = load_credentials(ENV_PATH)
    if not email or not token:
        raise RuntimeError("ATLASSIAN_EMAIL/ATLASSIAN_TOKEN missing")
    return ConfluencePuller(get_config(), email, token)


@app.get("/api/jobs/{job_id}/events")
async def job_events(job_id: str):
    job = JOBS.get(job_id)
    if not job:
        raise HTTPException(404, "job not found")

    async def gen():
        # Replay events that fired before client connected
        for past in list(job.events):
            yield {"event": past["kind"], "data": json.dumps(past)}
        # Stream new ones
        while True:
            try:
                ev = job.queue.get(timeout=0.5)
            except Empty:
                if job.status in ("done", "failed"):
                    break
                await asyncio.sleep(0.1)
                continue
            yield {"event": ev["kind"], "data": json.dumps(ev)}
            if ev["kind"] in ("stream_end", "job_error"):
                break

    return EventSourceResponse(gen())


