@app.get("/api/spaces")
def list_spaces() -> JSONResponse:
    """Return cached inventory + per-space enabled/disabled state from config."""
    config = get_config()
    if not config.inventory_path.exists():
        return JSONResponse({"spaces": [], "error": f"inventory missing at {config.inventory_path}"})
    # Inventory was generated by PowerShell on Windows, which emits a UTF-8 BOM.
    inv = json.loads(config.inventory_path.read_text(encoding="utf-8-sig"))
    spaces = []
    for s in inv:
        key = s.get("key")
        spaces.append({
            "key": key,
            "id": s.get("id"),
            "name": s.get("name"),
            "type": s.get("type"),
            "pages_current": s.get("pages_current", 0),
            "category": config.category_for(key),
            "enabled": config.is_enabled(key),
            "included": config.is_included(key, s.get("pages_current", 0)),
        })
    spaces.sort(key=lambda s: (not s["enabled"], -s["pages_current"]))
    return JSONResponse({
        "spaces": spaces,
        "total": len(spaces),
        "enabled_keys": config.enabled_keys,
        "min_pages_threshold": config.min_pages_threshold,
    })


