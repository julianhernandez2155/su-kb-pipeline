@app.get("/api/pages")
def list_pages_endpoint(space: str | None = None) -> dict[str, Any]:
    config = get_config()
    root = config.raw_path
    pages = []
    if not root.exists():
        return {"pages": [], "total": 0}
    for md in root.rglob("*.md"):
        fm = _read_frontmatter(md)
        if space and fm.get("space_key") != space:
            continue
        pages.append({
            "page_id": fm.get("page_id"),
            "title": fm.get("title"),
            "space_key": fm.get("space_key"),
            "ancestor_path": fm.get("ancestor_path"),
            "last_modified": fm.get("last_modified"),
            "version": fm.get("version"),
            "maintenance_signal": fm.get("maintenance_signal"),
            "last_sync_status": fm.get("last_sync_status"),
            "warnings_count": len(fm.get("conversion_warnings") or []),
            "path": str(md.relative_to(root)),
        })
    pages.sort(key=lambda p: (p.get("space_key") or "", p.get("title") or ""))
    return {"pages": pages, "total": len(pages)}


@app.get("/api/pages/{page_id}")
def get_page_endpoint(page_id: str) -> dict[str, Any]:
    config = get_config()
    md_path = _find_page(config.raw_path, page_id)
    if not md_path:
        raise HTTPException(404, f"page {page_id} not found in {config.raw_path}")
    text = md_path.read_text(encoding="utf-8")
    fm, body = _split_frontmatter(text)

    # Look for the dead-letter entry if we still have the raw XML
    dl_root = config.output_dir / "conversion-failures"
    raw_xml_hint = None
    if dl_root.exists():
        for f in dl_root.rglob(f"{page_id}.json"):
            try:
                raw_xml_hint = load_failure(f).get("storage_xml")
                break
            except Exception:
                pass

    return {
        "page_id": page_id,
        "frontmatter": fm,
        "markdown": body,
        "path": str(md_path),
        "storage_xml": raw_xml_hint,  # null unless this page was previously dead-lettered
    }


