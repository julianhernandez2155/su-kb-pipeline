@app.post("/api/query")
def post_query(body: dict[str, Any]) -> JSONResponse:
    """Answer a single question against the corpus. v1.5 chat-interface entrypoint.

    Body: {question: str, mode: "raw" | "raw+wiki" (default "raw+wiki"),
           max_pages: int? (default no cap)}
    """
    question = (body.get("question") or "").strip()
    if not question:
        raise HTTPException(400, "question is required")
    mode = body.get("mode") or "raw+wiki"
    if mode not in ("raw", "raw+wiki"):
        raise HTTPException(400, f"mode must be 'raw' or 'raw+wiki', got {mode!r}")
    max_pages = body.get("max_pages")

    try:
        result = query_mod.answer_query(
            question=question,
            config=get_config(),
            mode=mode,
            max_pages=int(max_pages) if max_pages else None,
        )
    except RuntimeError as e:
        # ANTHROPIC_API_KEY missing or SDK not installed — surface clearly.
        raise HTTPException(503, str(e))
    return JSONResponse(result.to_dict())


