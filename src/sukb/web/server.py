@app.post("/api/failures/{page_id}/retry")
def retry_failure(page_id: str) -> dict[str, Any]:
    config = get_config()
    dl_root = config.output_dir / "conversion-failures"
    matches = list(dl_root.rglob(f"{page_id}.json"))
    if not matches:
        raise HTTPException(404, "no failure record for that page_id")
    failure = load_failure(matches[0])
    space_key = failure.get("space_key")
    if not space_key:
        raise HTTPException(400, "failure record has no space_key")

    # For v1 retry = re-run the whole space. Single-page retry is v1.5 (needs a
    # narrower puller entrypoint).
    with JOBS_LOCK:
        active = [j for j in JOBS.values() if j.space_key == space_key and j.status in ("pending", "running")]
        if active:
            raise HTTPException(
                409,
                detail=f"Space {space_key} already has an active pull (job_id={active[0].job_id}).",
            )
        job_id = uuid.uuid4().hex[:12]
        job = Job(job_id=job_id, space_key=space_key, started_at=_now())
        JOBS[job_id] = job
    # Clear the failure record so the retry's outcome is the new authoritative one.
    clear_failure(matches[0])
    threading.Thread(target=_run_pull, args=(job,), daemon=True).start()
    return {"job_id": job_id, "space_key": space_key, "note": "v1 retry triggers a full-space re-pull"}


