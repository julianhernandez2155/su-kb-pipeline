def _load_env_file(env_path: Path) -> None:
    """Populate os.environ from .env at module import so secrets (Atlassian
    + Anthropic) are available to every endpoint, not just the auth path."""
    if not env_path.exists():
        return
    try:
        from dotenv import load_dotenv
        load_dotenv(env_path)
    except ImportError:
        for line in env_path.read_text(encoding="utf-8").splitlines():
            if "=" in line and not line.startswith("#"):
                k, _, v = line.partition("=")
                os.environ.setdefault(k.strip(), v.strip().strip('"').strip("'"))


_load_env_file(ENV_PATH)


@dataclass
class Job:
    job_id: str
    space_key: str
    status: str = "pending"  # pending | running | done | failed
    events: list[dict[str, Any]] = field(default_factory=list)
    queue: Queue = field(default_factory=Queue)
    summary: dict[str, Any] | None = None
    started_at: str = ""
    finished_at: str = ""
    error: str | None = None


# In-memory job registry. Single-process v1 — Redis/RQ comes later if needed.
JOBS: dict[str, Job] = {}
JOBS_LOCK = threading.Lock()


def get_config() -> SyncConfig:
    return SyncConfig.load(CONFIG_PATH)


def get_puller() -> ConfluencePuller:
    email, token = load_credentials(ENV_PATH)
    if not email or not token:
        raise HTTPException(
            status_code=503,
            detail="ATLASSIAN_EMAIL or ATLASSIAN_TOKEN missing from environment / .env",
        )
    return ConfluencePuller(get_config(), email, token)


